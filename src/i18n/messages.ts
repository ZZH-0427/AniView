export type MessageKey = keyof typeof catalog
export type MessageParams = Readonly<Record<string, string | number>>
export interface Message { readonly key: MessageKey; readonly params?: MessageParams }
export type MessageDictionary = Readonly<Record<MessageKey, string>>
const pick = (column: 0 | 1): MessageDictionary => Object.fromEntries(
  Object.entries(catalog).map(([key, pair]) => [key, pair[column]]),
) as MessageDictionary // All keys originate from the fully typed bilingual catalog above.
export const messages = { en: pick(0), 'zh-CN': pick(1) } satisfies Record<Locale, MessageDictionary>

export function translate(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  const template = messages[locale][key]
  if (typeof template !== 'string') {
    if (import.meta.env.DEV) throw new Error(`Missing translation: ${key}`)
    return messages[locale]['errors.generic']
  }
  let missing = false
  const text = template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = params[name]
    if (value === undefined) { missing = true; return '' }
    return String(value)
  })
  if (missing) {
    if (import.meta.env.DEV) throw new Error(`Missing translation parameters: ${key}`)
    return messages[locale]['errors.generic']
  }
  return text
}
export const translateMessage = (locale: Locale, message: Message) => translate(locale, message.key, message.params)
export const numberText = (locale: Locale, value: number, digits?: number) => new Intl.NumberFormat(locale,
  digits === undefined ? {} : { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(value)
